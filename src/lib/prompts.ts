export function interviewerStatus(opts: {
  kind: WindowKind;
  userTurns: number;
  softLimit: number;
  targets?: TargetSelection;
  coverage?: Partial<Record<CoverageKey, CoverageValue>>;
  retryNote?: string;
}): string {
  const lines = ["## 현재 상태", `- 이 창에서 사용자가 말한 횟수: ${opts.userTurns}`];
  if (opts.coverage) {
    lines.push(`- 직전 턴에 기록한 coverage(대화를 다시 확인해 이번 턴에 정확히 갱신하세요): ${JSON.stringify(opts.coverage)}`);
  }
  if ((opts.kind === "exp1" || opts.kind === "exp2") && opts.targets) {
    lines.push(
      `- 사용자가 앞서 10초 안에 고른 대상(화면 맨 위에 떠 있음): ${opts.targets.survivors.map((s) => s.name).join(" / ")}`,
      "  → 이 대상은 경험을 떠올리는 입구일 뿐, 경험의 범위를 제한하지 않습니다.",
    );
  }
  if (opts.userTurns >= opts.softLimit) {
    lines.push("- 대화가 충분히 길어졌습니다. 꼭 필요한 질문만 하고 재진술 카드로 마무리하세요.");
  }
  if (opts.retryNote) lines.push(`- ${opts.retryNote}`);
  return lines.join("\n");
}

