export async function participantSays(messages: { role: string; content: string }[], kind: WindowKind): Promise<string> {
  const transcript = messages.map((m) => `${m.role === "user" ? "참가자(나)" : "인터뷰어"}: ${m.content}`).join("\n");
  const res = await anthropic().messages.create({
    model: "claude-sonnet-5",
    max_tokens: 700,
    thinking: { type: "disabled" },
    output_config: { effort: "low" },
    system: `${pickPersona()}\n\n${WINDOW_HINT[kind]}`,
    messages: [{ role: "user", content: `지금까지의 대화:\n${transcript}\n\n다음에 내가 입력할 말만 쓰세요.` }],
  });
  return res.content
    .filter((b) => b.type === "text")
    .map((b) => (b as { text: string }).text)
    .join("\n")
    .trim();
}

